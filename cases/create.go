// ValidationError is a case-creation error caused by bad input (missing or
// invalid fields). It is returned by Create so HTTP handlers can map it to a
// 400 without leaking internal errors.
type ValidationError string

func (e ValidationError) Error() string { return string(e) }

// CreateInput is what the API's create-case endpoint needs: the case's type
// (CRIMINAL/CIVIL), its modality and a description. The case_id is generated by
// TrackID, not supplied.
type CreateInput struct {
	CaseType    string
	Modality    string
	Description string
	// CreatedBy is the user creating the case, 0 when none. Their unit on the day (organizations.UnitOn)
	// becomes the case's unit and is what a Numbering sees; without one the case goes to the unit that
	// receives new cases.
	CreatedBy int64
}

// NewCase is what a Numbering is given to number a case about to be created.
type NewCase struct {
	Modality string // FACIAL or FINGERPRINT
	Year     int
	// UnitID is the unit the case will belong to: the creator's, else the one receiving new cases.
	UnitID int64
}

// Number is a new case's identifier. Year and Number fill case_year and case_number, which are unique
// together: a Numbering whose own scheme counts differently (per unit, say) leaves both nil.
type Number struct {
	CaseID string
	Year   *int32
	Number *int32
}

// Numbering numbers a new case inside its transaction. It may read q to count, and returns
// ValidationError for a case it cannot number. A concurrent create can take the same CaseID; the
// whole transaction is then retried (IsDuplicateNumber).
type Numbering func(ctx context.Context, q *db.Queries, c NewCase) (Number, error)

var numbering Numbering = defaultNumbering

// RegisterNumbering replaces how cases are numbered, "2026.0001" by default (an organization numbers
// by its own scheme, as PF does). Call it before serving.
func RegisterNumbering(n Numbering) { numbering = n }

func defaultNumbering(ctx context.Context, q *db.Queries, c NewCase) (Number, error) {
	maxNumber, err := q.MaxCaseNumberForYear(ctx, int32(c.Year))
	if err != nil {
		return Number{}, fmt.Errorf("cases: read max case number: %w", err)
	}
	year, number := int32(c.Year), maxNumber+1
	return Number{CaseID: fmt.Sprintf("%04d.%04d", year, number), Year: &year, Number: &number}, nil
}

// maxNumberingAttempts bounds how many times Create retries when a concurrent
// create raced to the same (year, number). See isDuplicateNumber.
const maxNumberingAttempts = 3

// Create inserts a new biometric case, generating its "<year>.<sequence>"
// case_id (e.g. "2026.0001") from the current year and the next sequential
// number for that year. Numbering is done in Go: the highest case_number for
// the year is read inside a transaction and incremented, and the unique
// (case_year, case_number) index is the only database-level enforcement
// against a duplicate.
func Create(ctx context.Context, sqlDB *sql.DB, input CreateInput) (Case, error) {
	if sqlDB == nil {
		return Case{}, fmt.Errorf("cases: nil db")
	}
	for attempt := 1; ; attempt++ {
		created, err := createNumbered(ctx, sqlDB, input)
		if err == nil {
			return created, nil
		}
		if !IsDuplicateNumber(err) || attempt >= maxNumberingAttempts {
			return Case{}, err
		}
	}
}

// createNumbered creates the case in a transaction of its own.
func createNumbered(ctx context.Context, sqlDB *sql.DB, input CreateInput) (Case, error) {
	tx, err := sqlDB.BeginTx(ctx, nil)
	if err != nil {
		return Case{}, err
	}
	defer tx.Rollback()
	created, _, err := CreateWith(ctx, db.New(tx), input)
	if err != nil {
		return Case{}, err
	}
	if err := tx.Commit(); err != nil {
		return Case{}, err
	}
	return created, nil
}

// CreateWith is Create on q, inside the caller's transaction (registering a request opens its
// cases this way): it validates input and numbers the case after the year's highest; the request
// opens its analyses. It returns the case and its row id. A concurrent create can take the same
// number; the caller retries its whole transaction when IsDuplicateNumber.
func CreateWith(ctx context.Context, q *db.Queries, input CreateInput) (Case, int64, error) {
	caseType := strings.ToUpper(strings.TrimSpace(input.CaseType))
	if !validCaseType(caseType) {
		return Case{}, 0, ValidationError("case_type must be CRIMINAL or CIVIL")
	}
	modality := strings.ToUpper(strings.TrimSpace(input.Modality))
	if modality != "FACIAL" && modality != "FINGERPRINT" {
		return Case{}, 0, ValidationError("modality must be FACIAL or FINGERPRINT")
	}
	description := strings.TrimSpace(input.Description)
	if description == "" {
		return Case{}, 0, ValidationError("description is required")
	}

	now := time.Now()
	var unit sql.NullInt64
	if input.CreatedBy != 0 {
		placed, err := organizations.UnitOn(ctx, q, input.CreatedBy, now)
		if err != nil {
			return Case{}, 0, err
		}
		if placed != nil {
			unit = sql.NullInt64{Int64: placed.UnitID, Valid: true}
		}
	}
	if !unit.Valid {
		id, err := q.DefaultCaseUnit(ctx)
		if err != nil {
			return Case{}, 0, fmt.Errorf("cases: unit receiving new cases: %w", err)
		}
		unit = sql.NullInt64{Int64: id, Valid: true}
	}
	number, err := numbering(ctx, q, NewCase{Modality: modality, Year: now.Year(), UnitID: unit.Int64})
	if err != nil {
		return Case{}, 0, err
	}

	row, err := q.CreateBiometricCase(ctx, db.CreateBiometricCaseParams{
		CaseID:      number.CaseID,
		CaseType:    caseType,
		Modality:    modality,
		Description: description,
		CaseYear:    nullInt32(number.Year),
		CaseNumber:  nullInt32(number.Number),
		UnitID:      unit,
	})
	if err != nil {
		return Case{}, 0, fmt.Errorf("cases: create biometric case: %w", err)
	}
	return Case{CaseID: row.CaseID, CaseType: row.CaseType, Modality: row.Modality, Description: row.Description}, row.ID, nil
}

// IsDuplicateNumber reports whether err is a unique violation on the
// (case_year, case_number) index — the signature of a concurrent create that
// raced for the same number.
func IsDuplicateNumber(err error) bool {
	return err != nil && strings.Contains(err.Error(), "biometric_cases_year_number_key") || strings.Contains(err.Error(), "biometric_cases_case_id_key")
}

func nullInt32(v *int32) sql.NullInt32 {
	if v == nil {
		return sql.NullInt32{}
	}
	return sql.NullInt32{Int32: *v, Valid: true}
}

